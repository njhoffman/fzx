#!/usr/bin/env bash
# colors presets-gen: presets.tsv from a checkout of base16-fzf (https://github.com/tinted-theming/base16-fzf,
# MIT): its bash/*.config files, one per scheme. `just presets DIR` (or `bash presets-gen.sh DIR > presets.tsv`).
# Rows are "slug<TAB>name<TAB>author<TAB>base00 ... base0F", the 16 colors as rrggbb, sorted by slug.

dir="${1:?usage: presets-gen.sh BASE16_FZF_DIR}"
[[ -d "$dir/bash" ]] || { printf 'presets-gen: no bash/ under %s\n' "$dir" >&2; exit 1; }

printf '# base16 color schemes for colors:presets, generated by presets-gen.sh from base16-fzf\n'
printf '# (https://github.com/tinted-theming/base16-fzf, MIT License, Copyright (c) 2017 nicodebo; the schemes\n'
printf '# are their authors'"'"', named in the third field). slug, name, author, base00 ... base0F (rrggbb)\n'
for f in "$dir"/bash/*.config; do
  awk -v slug="$(basename "$f" .config)" '
    BEGIN { sub(/^base16-/, "", slug) }
    /^# Base16 / && name == "" { name = substr($0, 10) }
    /^# Scheme author: / && author == "" { author = substr($0, 18) }
    /^# Author: / && author == "" { author = substr($0, 11) }
    match($0, /^local color0[0-9A-F]=.#[0-9a-fA-F]{6}/) { c[++n] = tolower(substr($0, RLENGTH - 5, 6)) }
    END {
      if (n != 16 || name == "") { print "presets-gen: skipped " FILENAME > "/dev/stderr"; exit }
      gsub(/\t/, " ", name); gsub(/\t/, " ", author)
      printf "%s\t%s\t%s", slug, name, author
      for (i = 1; i <= 16; i++) printf "\t%s", c[i]
      printf "\n"
    }' "$f"
done | LC_ALL=C sort -t $'\t' -k1,1
